"""Turns the fetched word recordings into small Opus files and web/js/data/speechlist.js. Run after fetch_speech.py. Run with python -I."""
import json, os, re, shutil, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'src')
OUT = os.path.join(ROOT, 'web', 'audio', 's'); os.makedirs(OUT, exist_ok=True)
FF = shutil.which('ffmpeg')
m = json.load(open(os.path.join(SRC, 'speech-map.json'), encoding='utf-8'))
items = [(k, v) for k, v in m.items() if v and v.get('file') and os.path.exists(os.path.join(SRC, 'speech-raw', v['file']))]
def one(job):
    i, (k, v) = job
    out = os.path.join(OUT, str(i) + '.ogg')
    r = subprocess.run([FF, '-y', '-v', 'error', '-i', os.path.join(SRC, 'speech-raw', v['file']), '-map_metadata', '-1', '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-18:TP=-2', '-ar', '48000', '-c:a', 'libopus', '-b:a', '24k', '-ac', '1', out], capture_output=True)
    return (k, i) if r.returncode == 0 and os.path.getsize(out) > 200 else None
with ThreadPoolExecutor(max_workers=max(2, (os.cpu_count() or 4) - 2)) as ex: done = [x for x in ex.map(one, enumerate(items)) if x]
speech = {}; credits = {}
for k, i in done:
    lang, w = k.split(':', 1); speech[w] = i
    v = m[k]; a = v.get('artist') or 'Lingua Libre contributor'; credits.setdefault(a + ' (' + (v.get('licence') or 'free licence') + ')', 0); credits[a + ' (' + (v.get('licence') or 'free licence') + ')'] += 1
with open(os.path.join(ROOT, 'web', 'js', 'data', 'speechlist.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('/* Generated by tools/make_speech.py: real people saying these words, from Lingua Libre on Wikimedia Commons. */\nwindow.SPEECH=' + json.dumps(speech, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.SPEECH_CREDITS=' + json.dumps(sorted(credits), ensure_ascii=False) + ';\n')
print('words', len(speech), 'MB', round(sum(os.path.getsize(os.path.join(OUT, x)) for x in os.listdir(OUT)) / 1e6, 1), 'speakers', len(credits))
